from __future__ import annotations

from pathlib import Path


def build_bwrap_args(
    user: str,
    home_dir: Path,
    proxy_ip: str,
    proxy_port: int,
    command: list[str],
    ca_cert_path: Path | None = None,
    extra_env: dict[str, str] | None = None,
    shared_packages_dir: Path = Path("/opt/pa"),
) -> list[str]:
    """Generate Bubblewrap (bwrap) argument list for Linux agent sandboxing."""
    cert_path = ca_cert_path or Path("/opt/pa/certs/mitmproxy-ca-cert.pem")
    workspace_dir = home_dir / "workspace"

    args: list[str] = [
        "bwrap",
        "--unshare-pid",
        "--unshare-ipc",
        "--unshare-uts",
        "--die-with-parent",
        "--ro-bind",
        "/usr",
        "/usr",
        "--ro-bind",
        "/bin",
        "/bin",
        "--ro-bind-try",
        "/lib",
        "/lib",
        "--ro-bind-try",
        "/lib64",
        "/lib64",
        "--ro-bind-try",
        "/etc/resolv.conf",
        "/etc/resolv.conf",
        "--ro-bind-try",
        "/etc/pki",
        "/etc/pki",
        "--ro-bind-try",
        "/etc/ssl",
        "/etc/ssl",
        "--ro-bind-try",
        str(shared_packages_dir),
        str(shared_packages_dir),
        "--proc",
        "/proc",
        "--dev",
        "/dev",
        "--dev-bind-try",
        "/dev/dri",
        "/dev/dri",
        "--dev-bind-try",
        "/dev/kfd",
        "/dev/kfd",
        "--dev-bind-try",
        "/dev/nvidia0",
        "/dev/nvidia0",
        "--dev-bind-try",
        "/dev/nvidiactl",
        "/dev/nvidiactl",
        "--dev-bind-try",
        "/dev/nvidia-uvm",
        "/dev/nvidia-uvm",
        "--tmpfs",
        "/tmp",
        "--tmpfs",
        "/run",
        "--tmpfs",
        "/home",
        "--bind",
        str(home_dir),
        str(home_dir),
        "--chdir",
        str(workspace_dir if workspace_dir.exists() else home_dir),
        "--setenv",
        "HOME",
        str(home_dir),
        "--setenv",
        "USER",
        user,
        "--setenv",
        "HTTP_PROXY",
        f"http://{proxy_ip}:{proxy_port}",
        "--setenv",
        "HTTPS_PROXY",
        f"http://{proxy_ip}:{proxy_port}",
        "--setenv",
        "http_proxy",
        f"http://{proxy_ip}:{proxy_port}",
        "--setenv",
        "https_proxy",
        f"http://{proxy_ip}:{proxy_port}",
        "--setenv",
        "SSL_CERT_FILE",
        str(cert_path),
        "--setenv",
        "NODE_EXTRA_CA_CERTS",
        str(cert_path),
        "--setenv",
        "REQUESTS_CA_BUNDLE",
        str(cert_path),
    ]

    if extra_env:
        for k, v in sorted(extra_env.items()):
            args.extend(["--setenv", k, v])

    args.extend(command)
    return args
